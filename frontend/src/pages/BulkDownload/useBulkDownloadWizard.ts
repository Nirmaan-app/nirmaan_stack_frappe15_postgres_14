import { useState, useCallback, useMemo } from "react";
import { useToast } from "@/components/ui/use-toast";
import { useFrappeGetCall, useFrappeGetDocList } from "frappe-react-sdk";
import { useUserData } from "@/hooks/useUserData";
import { useProjectPOTaskLinks } from "@/pages/projects/data/critical-po/useCriticalPOQueries";
import { attachLinkedPOs } from "@/pages/projects/CriticalPOTasks/utils";
import { ALL_SCOPE_MAX_ITEMS, BulkDocType, BulkDownloadScope, InvoiceSubType, bulkTableLimits, compareMtcs, isOverSelectionLimit } from "@/utils/bulkDownload/bulkDownloadTypes";
import { useBulkDownloadOperation } from "@/hooks/useBulkDownloadOperation";
import { runDetails } from "@/utils/bulkDownload/bulkDownloadRun";
import { usePorterInvoices } from "./usePorterInvoices";

export type { BulkDocType, InvoiceSubType };

/** Vendor scope only: the facet column is the project, not the vendor. */
interface ProjectFields {
    project?: string;
    project_name?: string;
}

export interface POItem extends ProjectFields {
    name: string;
    vendor_name?: string;
    vendor?: string;
    status?: string;
    amount?: number;
    total_amount?: number;
    creation?: string;
    latest_delivery_date?: string;
}

import { VendorInvoice as BaseVendorInvoice } from "@/types/NirmaanStack/VendorInvoice";
export interface VendorInvoice extends BaseVendorInvoice {
    vendor_name?: string;
    project_name?: string;
}

import { PODeliveryDocuments as BasePODeliveryDocuments } from "@/types/NirmaanStack/PODeliveryDocuments";
export interface PODeliveryDocuments extends BasePODeliveryDocuments {
    vendor_name?: string;
    project_name?: string;
    dc_date?: string;
}

import { ProjectInvoice as BaseProjectInvoice } from "@/types/NirmaanStack/ProjectInvoice";
export interface ProjectInvoice extends BaseProjectInvoice {
    company_name?: string;
    /** All scope only: the facet column next to the customer. */
    project_name?: string;
}

export interface WOItem extends ProjectFields {
    name: string;
    vendor?: string;
    vendor_name?: string;
    status?: string;
    total_amount?: number;
    creation?: string;
}
/** A paid PO or WO payment (`document_name` is the PO / WO). A WO row carries its uploaded voucher;
 *  a PO row's voucher is generated by the server. */
export interface PaymentVoucherRow extends ProjectFields {
    name: string;
    document_name?: string;
    vendor?: string;
    vendor_name?: string;
    amount?: number;
    utr?: string;
    payment_date?: string;
    voucher_attachment?: string;
    creation?: string;
}

import type { MaterialTestCertificate } from "@/types/NirmaanStack/MaterialTestCertificate";
/** One Material Test Certificate (one row per certificate, like a DC); its id is a key only, never shown. */
export type MTCRow = MaterialTestCertificate;

/** The Done step's "N … have been downloaded" noun, where the type id would not read well. */
const DONE_LABEL: Partial<Record<BulkDocType, string>> = { POPaymentVoucher: "PO Payment Voucher", WOPaymentVoucher: "WO Payment Voucher" };

export interface NirmaanAttachmentStub {
    name: string;
    attachment_type?: string;
    associated_docname?: string;
}

export interface CriticalPOTask {
    name: string;
    item_name: string;
    critical_po_category?: string;
    /** POs linked to this task (Critical PO Task Child Table), attached client-side. */
    linked_pos?: string[];
}

/**
 * The wizard for one project, one vendor or every project the user may read (the "all" scope).
 * `types` is `allowedBulkTypes(scope, role)`: the payment-voucher (PO, WO) and MTC lists are only
 * fetched where their card is offered.
 */
export const useBulkDownloadWizard = (scope: BulkDownloadScope, types: BulkDocType[]) => {
    const { kind, id } = scope;
    const isProject = kind === "project";
    const isAll = kind === "all";
    // The all scope has no scope filter: every list reads as the user (get_list), so their
    // permissions are the limit -- a PM sees only their own projects' rows.
    const scopeFilters: [string, "=", string][] = isAll ? [] : [[kind, "=", id]];
    const scopeKey = isAll ? "all" : id ? `${kind}-${id}` : null;
    // The facet column of a vendor's tables is the project (a project's tables show the vendor).
    const projectFields = isProject ? [] : ["project", "project.project_name"];

    const { toast } = useToast();
    const { role } = useUserData();
    const isProjectManager = role === "Nirmaan Project Manager Profile";

    const [step, setStep] = useState<1 | 2 | 3>(1);
    const [docType, setDocType] = useState<BulkDocType | null>(null);
    const [downloadedCount, setDownloadedCount] = useState(0);
    const [downloadedLabel, setDownloadedLabel] = useState("");
    const [selectedIds, setSelectedIds] = useState<string[]>([]);
    const [withRate, setWithRate] = useState(true);
    const [invoiceSubType, setInvoiceSubTypeState] = useState<InvoiceSubType>("All Invoices");

    // The download this wizard follows (ADR 0047): the progress window stays open on the outcome (ready /
    // failed) until closed, and a reload of the tab picks the download up again. Only a delivered file moves
    // the wizard to Done: a failed download keeps its selection.
    const download = useBulkDownloadOperation({
        storageKey: `bulk_wizard:${kind}:${isAll ? "all" : id}`,
        onSaved: (result, context) => {
            // The file's own count: a document that failed is not in the file.
            setDownloadedCount(result.included ?? 1);
            setDownloadedLabel(DONE_LABEL[context.type] ?? context.type);
            setStep(3);
        },
    });
    const { run, working: showProgress } = download;

    // A project or vendor loads every list up front (they are small, and Step 1 shows their counts).
    // The all scope loads ONLY the list of the type opened: company-wide they run to thousands of
    // rows each, so opening the tab fetches nothing. PO and DN share one list.
    const wants = (...listTypes: BulkDocType[]) => !isAll || (docType !== null && listTypes.includes(docType));

    const { data: poList = [], isLoading: posLoading } = useFrappeGetDocList<POItem>(
        "Procurement Orders",
        {
            fields: ["name", "vendor_name", "vendor", "status", "amount", "total_amount", "creation", "latest_delivery_date", ...(isProject ? [] : (["project", "project_name"] as const))],
            filters: [...scopeFilters, ["status", "not in", ["Merged", "Inactive", "Cancelled"]]],
            limit: 0,
            orderBy: { field: "creation", order: "asc" },
        },
        scopeKey && wants("PO", "DN") ? `bulk-po-${scopeKey}` : null
    );

    const { data: woList = [], isLoading: wosLoading } = useFrappeGetDocList<WOItem>(
        "Service Requests",
        {
            fields: ["name", "vendor", "vendor.vendor_name" as any, "status", "total_amount", "creation", ...projectFields as any[]],
            filters: [...scopeFilters, ["status", "=", "Approved"]],
            limit: 0,
            orderBy: { field: "`tabService Requests`.creation", order: "asc" },
        },
        scopeKey && wants("WO") ? `bulk-wo-${scopeKey}` : null
    );

    const { data: vendorInvoices = [], isLoading: invoicesLoading } = useFrappeGetDocList<VendorInvoice>(
        "Vendor Invoices",
        {
            fields: ["name", "vendor", "vendor.vendor_name" as any, "document_type", "document_name", "invoice_no", "invoice_date", "invoice_amount", "invoice_attachment", ...projectFields as any[]],
            filters: [...scopeFilters, ["status", "=", "Approved"]],
            limit: 0,
            orderBy: { field: "`tabVendor Invoices`.creation", order: "asc" },
        },
        scopeKey && wants("Invoice") ? `bulk-vi-${scopeKey}` : null
    );

    // PO-only by design: the Bulk Download wizard's UX (vendor facet, vendor_name
    // subtitle, parent search) is built for PO-parented PDDs. Since
    // `PO Delivery Documents` is polymorphic (PO + ITM share the table), an
    // unfiltered fetch would mix in ITM rows that show as anonymous entries.
    // Filter on `parent_doctype = "Procurement Orders"` — backfill patch
    // populates this field for every legacy PO PDD, and the create API stamps
    // it on every new row. ITM bulk download, if needed later, is a separate flow.
    const { data: poDeliveryDocs = [], isLoading: poDeliveryDocsLoading } = useFrappeGetDocList<PODeliveryDocuments>(
        "PO Delivery Documents",
        {
            fields: ["name", "vendor", "vendor.vendor_name" as any, "type", "parent_docname", "procurement_order", "creation", "nirmaan_attachment", "dc_date", "reference_number", "dc_reference", ...projectFields as any[]],
            filters: [
                ...scopeFilters,
                ["parent_doctype", "=", "Procurement Orders"],
            ],
            limit: 0,
            orderBy: { field: "`tabPO Delivery Documents`.dc_date", order: "asc" },
        },
        scopeKey && wants("DC", "MIR") ? `bulk-podd-${scopeKey}` : null
    );

    const { data: projectInvoices = [], isLoading: projectInvoicesLoading } = useFrappeGetDocList<ProjectInvoice>(
        "Project Invoices",
        {
            fields: ["name", "customer", "customer.company_name" as any, "invoice_no", "invoice_date", "amount", "attachment", "creation", ...(isAll ? projectFields as any[] : [])],
            filters: [...scopeFilters],
            limit: 0,
            orderBy: { field: "`tabProject Invoices`.invoice_date", order: "asc" },
        },
        // Project Invoices carry no vendor.
        (isProject || isAll) && scopeKey && wants("ClientInvoice") ? `bulk-pi-${scopeKey}` : null
    );

    const { data: rawCriticalTasks, isLoading: criticalTasksListLoading } = useFrappeGetDocList<CriticalPOTask>(
        "Critical PO Tasks",
        {
            fields: ["name", "item_name", "critical_po_category"],
            filters: [...scopeFilters],
            limit: 0,
            orderBy: { field: "creation", order: "desc" },
        },
        // Critical PO Tasks exist only inside a project.
        isProject && scopeKey ? `bulk-critical-${scopeKey}` : null
    );

    // Which POs each task has comes from the Critical PO Task Child Table.
    const { taskPOMap, isLoading: criticalLinksLoading } = useProjectPOTaskLinks(isProject ? id : "", isProject && !!id);
    const criticalTasks = useMemo(
        () => attachLinkedPOs(rawCriticalTasks, taskPOMap) ?? [],
        [rawCriticalTasks, taskPOMap]
    );
    const criticalTasksLoading = criticalTasksListLoading || criticalLinksLoading;

    const paymentFields = ["name", "document_name", "project", "project.project_name" as any, "vendor", "vendor.vendor_name" as any, "amount", "utr", "payment_date", "creation"];
    // Both voucher lists wait out the role's "Loading" placeholder, which would otherwise fetch them for a PM too.
    // WO: only the paid payments that HAVE an uploaded voucher -- one without has nothing to download.
    const { data: woVoucherPayments = [], isLoading: woVouchersLoading } = useFrappeGetDocList<PaymentVoucherRow>(
        "Project Payments",
        {
            fields: [...paymentFields, "voucher_attachment"],
            // The SDK's filter type has no "is" operator; Frappe does ("is set" = neither null nor "").
            filters: [...scopeFilters, ["document_type", "=", "Service Requests"], ["status", "=", "Paid"], ["voucher_attachment", "is", "set"] as any],
            limit: 0,
            orderBy: { field: "`tabProject Payments`.payment_date", order: "asc" },
        },
        types.includes("WOPaymentVoucher") && role !== "Loading" && scopeKey && wants("WOPaymentVoucher") ? `bulk-pay-wo-${scopeKey}` : null
    );
    // PO: only Paid payments -- PO payments have no uploaded voucher, so the server generates each one,
    // and a voucher exists only for a payment made (the PO page offers it for Paid payments only).
    const { data: poVoucherPayments = [], isLoading: poVouchersLoading } = useFrappeGetDocList<PaymentVoucherRow>(
        "Project Payments",
        {
            fields: paymentFields,
            filters: [...scopeFilters, ["document_type", "=", "Procurement Orders"], ["status", "=", "Paid"]],
            limit: 0,
            orderBy: { field: "`tabProject Payments`.payment_date", order: "asc" },
        },
        types.includes("POPaymentVoucher") && role !== "Loading" && scopeKey && wants("POPaymentVoucher") ? `bulk-pay-po-${scopeKey}` : null
    );

    // One row per certificate, through the MTC module's own read (`get_mtcs`), which applies the MTC
    // page's project rule: a PM / PL sees only their assigned projects.
    const { data: mtcData, isLoading: mtcsLoading } = useFrappeGetCall<{ message: MTCRow[] }>(
        "nirmaan_stack.api.material_test_certificates.mtc_api.get_mtcs",
        isAll ? { all_projects: 1 } : { [kind]: id },
        types.includes("MTC") && scopeKey && wants("MTC") ? `bulk-mtc-${scopeKey}` : null,
        { revalidateOnFocus: false }
    );
    // Oldest certificate first, undated ones last -- the order the merged PDF holds them in.
    const mtcItems = useMemo(
        () => [...(mtcData?.message ?? [])].filter((m) => !!m.attachment).sort(compareMtcs),
        [mtcData]
    );

    // Porter invoices: Report Bulk Download only, loaded only when the card is opened.
    const { porterInvoices, porterInvoicesLoading } = usePorterInvoices(isAll && types.includes("PorterInvoice") && role !== "Loading" && wants("PorterInvoice"));

    // Every step filters inside its own selection table (facet + date column filters), so the hook
    // hands each step its full ELIGIBLE list: DN = POs that have deliveries; the attachment types =
    // rows that actually carry a file to merge.
    const dnList = useMemo(() => poList.filter(p => ["Delivered", "Partially Delivered"].includes(p.status!)), [poList]);
    const invoiceItems = useMemo(() => vendorInvoices.filter(v => !!v.invoice_attachment), [vendorInvoices]);
    const dcItems = useMemo(() => poDeliveryDocs.filter(d => d.type === "Delivery Challan" && !!d.nirmaan_attachment), [poDeliveryDocs]);
    const mirItems = useMemo(() => poDeliveryDocs.filter(d => d.type === "Material Inspection Report" && !!d.nirmaan_attachment), [poDeliveryDocs]);
    const projectInvoiceItems = useMemo(() => projectInvoices.filter(p => !!p.attachment), [projectInvoices]);

    const filteredInvoiceItems = useCallback((sub: InvoiceSubType) => {
        if (sub === "PO Invoices") return invoiceItems.filter(i => i.document_type === "Procurement Orders");
        if (sub === "WO Invoices") return invoiceItems.filter(i => i.document_type === "Service Requests");
        return invoiceItems;
    }, [invoiceItems]);

    const itemCounts = useMemo(() => ({
        PO: poList.length, WO: woList.length, Invoice: invoiceItems.length,
        DC: dcItems.length, MIR: mirItems.length, DN: dnList.length,
        MTC: mtcItems.length, ClientInvoice: projectInvoiceItems.length,
        POPaymentVoucher: poVoucherPayments.length, WOPaymentVoucher: woVoucherPayments.length,
        PorterInvoice: porterInvoices.length,
    }), [porterInvoices, poList, woList, invoiceItems, dcItems, mirItems, dnList, mtcItems, projectInvoiceItems, poVoucherPayments, woVoucherPayments]);

    const goToStep2 = useCallback((t: BulkDocType) => { setDocType(t); setSelectedIds([]); setStep(2); }, []);
    const goBack = useCallback(() => { setStep(1); setDocType(null); setSelectedIds([]); }, []);
    const resetToTypeSelection = useCallback(() => { setStep(1); setDocType(null); setSelectedIds([]); setDownloadedCount(0); setDownloadedLabel(""); }, []);

    // Switching invoice type swaps the list under the table, so the selection goes with it -- a
    // download must never carry an invoice the current type hides.
    const setInvoiceSubType = useCallback((t: InvoiceSubType) => { setInvoiceSubTypeState(t); setSelectedIds([]); }, []);

    const toggleId = useCallback((id: string) => setSelectedIds(p => p.includes(id) ? p.filter(x => x !== id) : [...p, id]), []);
    const selectAll = useCallback((ids: string[]) => setSelectedIds(ids), []);
    const deselectAll = useCallback(() => setSelectedIds([]), []);

    // The DN step offers only POs with deliveries, so its Critical POs tab links only those: a task's
    // PO chips and count match what ticking it queues, and a task with no delivered PO drops out.
    const dnCriticalTasks = useMemo(() => {
        const delivered = new Set(dnList.map(p => p.name));
        return criticalTasks.map(t => ({ ...t, linked_pos: (t.linked_pos ?? []).filter(p => delivered.has(p)) }));
    }, [criticalTasks, dnList]);

    // Ticking tasks selects their POs from the CURRENT step's own list (DN: delivered POs only).
    const selectMultipleCriticalTaskPOs = useCallback((taskNames: string[]) => {
        const [tasks, eligible] = docType === "DN" ? [dnCriticalTasks, dnList] : [criticalTasks, poList];
        const all = new Set<string>();
        taskNames.forEach(n => (tasks.find(t => t.name === n)?.linked_pos ?? []).forEach(p => all.add(p)));
        setSelectedIds(eligible.filter(p => all.has(p.name)).map(p => p.name));
    }, [docType, criticalTasks, dnCriticalTasks, poList, dnList]);

    const handleDownload = async () => {
        if (showProgress || !docType) return;
        if (!selectedIds.length) { toast({ title: "No items selected", variant: "destructive" }); return; }
        // The button is disabled over the limit; this guards any other way in (the server refuses too).
        if (isOverSelectionLimit(selectedIds.length, bulkTableLimits(kind))) {
            toast({ title: "Too many items", description: `One download takes up to ${ALL_SCOPE_MAX_ITEMS}. Narrow the list with the filters.`, variant: "destructive" });
            return;
        }
        const rate = isProjectManager ? false : withRate;
        // The all scope sends no project or vendor; the server reads the selection as the user.
        const scopeArgs: Record<string, unknown> = isAll ? { all_scope: 1 } : { [kind]: id };
        const names = JSON.stringify(selectedIds);
        const attachments = (urls: (string | null | undefined)[]) => JSON.stringify(urls);
        const [endpoint, args]: [string, Record<string, unknown>] = (() => {
            switch (docType) {
                case "PO": return ["download_selected_pos", { names, with_rate: rate ? 1 : 0 }];
                case "WO": return ["download_selected_wos", { names, with_rate: rate ? 1 : 0 }];
                case "DN": return ["download_selected_dns", { names }];
                case "Invoice": return ["download_selected_attachments", {
                    doc_type: invoiceSubType,
                    attachment_names: attachments(filteredInvoiceItems(invoiceSubType).filter(i => selectedIds.includes(i.name)).map(i => i.invoice_attachment)),
                }];
                case "DC":
                case "MIR": return ["download_selected_attachments", {
                    doc_type: docType,
                    attachment_names: attachments((docType === "DC" ? dcItems : mirItems).filter(d => selectedIds.includes(d.name)).map(d => d.nirmaan_attachment)),
                }];
                case "ClientInvoice": return ["download_selected_attachments", {
                    doc_type: "Client Invoices",
                    attachment_names: attachments(projectInvoiceItems.filter(p => selectedIds.includes(p.name)).map(p => p.attachment)),
                }];
                // MTC names, not file URLs: the server reads each certificate back itself.
                case "MTC": return ["download_selected_mtcs", { names }];
                // Payment names: the server keeps the Paid ones and generates each voucher.
                case "POPaymentVoucher": return ["download_selected_po_payment_vouchers", { names }];
                // Payment names, not file URLs: the server reads each uploaded voucher back itself.
                case "WOPaymentVoucher": return ["download_selected_wo_payment_vouchers", { names }];
                // Invoice numbers, not file URLs: the server reads each invoice's own PDF back itself.
                case "PorterInvoice": return ["download_selected_porter_invoices", { names }];
            }
        })();
        // A refusal shows its reason in the progress window.
        await download.start(
            `nirmaan_stack.api.pdf_helper.bulk_download.${endpoint}`,
            { ...scopeArgs, ...args },
            {
                type: docType,
                details: runDetails(docType, {
                    selected: selectedIds.length,
                    withRate: rate,
                    invoiceType: docType === "Invoice" ? invoiceSubType : undefined,
                }),
            },
        );
    };

    return {
        step, docType, selectedIds, toggleId, selectAll, deselectAll, selectMultipleCriticalTaskPOs, goToStep2, goBack, resetToTypeSelection,
        downloadedCount, downloadedLabel, poList, posLoading, woList, wosLoading, dnList,
        invoicesLoading, dcItems, mirItems, poDeliveryDocsLoading, criticalTasks, dnCriticalTasks, criticalTasksLoading,
        withRate, setWithRate, itemCounts, invoiceSubType, setInvoiceSubType, filteredInvoiceItems,
        loading: showProgress, showProgress, run, closeProgress: download.close, handleDownload,
        cancelDownload: download.cancel,
        projectInvoiceItems,
        projectInvoicesLoading,
        poVoucherPayments,
        poVouchersLoading,
        woVoucherPayments,
        woVouchersLoading,
        mtcItems,
        mtcsLoading,
        porterInvoices,
        porterInvoicesLoading,
    };
};
