"""Write one TypeScript interface per DocType JSON into frontend/src/types/doctypes/ (ADR-0049).

    python3 scripts/generate_doctype_types.py           # regenerate the folder
    python3 scripts/generate_doctype_types.py --check   # exit 1 when the committed folder is stale (CI)

Stdlib only, so CI runs it without a bench.
"""

import argparse
import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DOCTYPE_ROOT = REPO_ROOT / "nirmaan_stack"
OUT_DIR = REPO_ROOT / "frontend" / "src" / "types" / "doctypes"
HEADER = ("// Generated by scripts/generate_doctype_types.py from the DocType JSON. Do not edit by hand: "
          "change the DocType, then run `python3 scripts/generate_doctype_types.py`.\n")

STANDARD_FIELDS = (
    "name: string",
    "owner: string",
    "creation: string",
    "modified: string",
    "modified_by: string",
    "docstatus?: 0 | 1 | 2",
    "idx?: number",
)
CHILD_FIELDS = ("parent: string", "parentfield: string", "parenttype: string")

STRING_TYPES = {
    "Data", "Small Text", "Text", "Long Text", "Text Editor", "HTML Editor", "Markdown Editor", "Code",
    "Link", "Dynamic Link", "Date", "Datetime", "Time", "Attach", "Attach Image", "Password", "Read Only",
    "Phone", "Color", "Barcode", "Signature", "Autocomplete", "Icon", "Geolocation",
}
NUMBER_TYPES = {"Int", "Float", "Currency", "Percent", "Rating", "Duration"}
LAYOUT_TYPES = {"Section Break", "Column Break", "Tab Break", "HTML", "Button", "Image", "Heading", "Fold"}
TABLE_TYPES = {"Table", "Table MultiSelect"}


def ts_type(f: dict) -> str:
    ft = f["fieldtype"]
    if ft in STRING_TYPES:
        return "string"
    if ft in NUMBER_TYPES:
        return "number"
    if ft == "Check":
        return "0 | 1"
    if ft == "JSON":
        return "unknown"
    if ft == "Select":
        options = list(dict.fromkeys(o.strip() for o in (f.get("options") or "").split("\n")))
        if options == [""]:
            return "string"
        return " | ".join(json.dumps(o, ensure_ascii=False) for o in options)
    if ft in TABLE_TYPES:
        return interface_name(f["options"]) + "[]"
    raise ValueError(f"field {f['fieldname']!r} has fieldtype {ft!r}, which has no TypeScript mapping; add it")


def doc_comment(f: dict) -> str:
    text = f"{f.get('label') or f['fieldname']} : {f['fieldtype']}"
    if f["fieldtype"] in {"Link", "Table", "Table MultiSelect"} and f.get("options"):
        text += f" - {f['options']}"
    return "/** " + text.replace("*/", "* /") + " */"


def module_name(doctype_name: str) -> str:
    """`Procurement Requests` -> `ProcurementRequests`: the generated file's name, without `.ts`."""
    words = re.split(r"[^A-Za-z0-9]+", doctype_name)
    return "".join(w[:1].upper() + w[1:] for w in words if w)


def interface_name(doctype_name: str) -> str:
    """`Procurement Requests` -> `ProcurementRequestsDocType`. The suffix keeps clear of the hand-kept names."""
    return module_name(doctype_name) + "DocType"


def render_interface(dt: dict) -> str:
    children = sorted({f["options"] for f in dt.get("fields", []) if f["fieldtype"] in TABLE_TYPES})
    lines = [f'import type {{ {interface_name(c)} }} from "./{module_name(c)}";' for c in children]
    if children:
        lines.append("")
    lines.append(f"export interface {interface_name(dt['name'])} {{")
    lines += [f"\t{f}" for f in STANDARD_FIELDS]
    if dt.get("istable"):
        lines += [f"\t{f}" for f in CHILD_FIELDS]
    for f in dt.get("fields", []):
        if f["fieldtype"] in LAYOUT_TYPES:
            continue
        optional = "" if f.get("reqd") else "?"
        lines += [f"\t{doc_comment(f)}", f"\t{f['fieldname']}{optional}: {ts_type(f)}"]
    lines.append("}")
    return "\n".join(lines) + "\n"


def doctype_jsons(root: Path) -> list[Path]:
    """Every `<root>/**/doctype/<folder>/<folder>.json` that defines a DocType."""
    return [p for p in sorted(root.glob("**/doctype/*/*.json"))
            if p.stem == p.parent.name and json.loads(p.read_text()).get("doctype") == "DocType"]


def render_folder(root: Path) -> dict[str, str]:
    """File name -> content for every DocType under ``root``."""
    files: dict[str, str] = {}
    for path in doctype_jsons(root):
        dt = json.loads(path.read_text())
        name = module_name(dt["name"]) + ".ts"
        if name in files:
            raise ValueError(f"two DocTypes map to {name}; rename one")
        files[name] = HEADER + "\n" + render_interface(dt)
    return files


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 when the folder is stale")
    ap.add_argument("--doctypes", type=Path, default=DOCTYPE_ROOT, help=argparse.SUPPRESS)
    ap.add_argument("--out", type=Path, default=OUT_DIR, help=argparse.SUPPRESS)
    args = ap.parse_args(argv)

    wanted = render_folder(args.doctypes)
    have = {p.name: p.read_text() for p in args.out.glob("*.ts")} if args.out.is_dir() else {}
    stale = sorted(n for n in wanted.keys() | have.keys() if wanted.get(n) != have.get(n))
    if args.check:
        if stale:
            print(f"{len(stale)} generated DocType type file(s) are stale: {', '.join(stale)}\n"
                  "Run python3 scripts/generate_doctype_types.py and commit the output.", file=sys.stderr)
            return 1
        return 0
    args.out.mkdir(parents=True, exist_ok=True)
    for name in stale:
        if name in wanted:
            (args.out / name).write_text(wanted[name])
        else:
            (args.out / name).unlink()
    print(f"{len(wanted)} DocTypes, {len(stale)} file(s) written or removed in {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
